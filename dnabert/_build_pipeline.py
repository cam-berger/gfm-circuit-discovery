"""Build the DNABERT-2 pipeline notebooks in Drive. Run from 00_setup.ipynb in Colab.

Two problems in the delivered zip are fixed here:

1. Notebooks 02-09 ship as Colab-generated .py exports, not notebooks. Markdown cells
   are triple-quoted blocks and code cells are the text between them, so they are
   reconstructed rather than executed as scripts (six of the eight are not even valid
   Python -- they contain bare markdown and !pip magics).
2. Notebook 01 never mounts Drive and saves to the relative path
   'outputs/promoter_baseline_pilot', which lands on the runtime-local disk and is lost
   when the VM ends. Notebook 02 loads the Layer-5 probe from the Drive copy, so the
   01 -> 02 handoff never happened. Only 01's destination changes; contents are identical.
"""

import ast
import json
import re
import shutil
import zipfile
from pathlib import Path

