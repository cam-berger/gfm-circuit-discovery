OLD_OUT = 'OUTPUT_DIR = Path("outputs/promoter_baseline_pilot")'


def patch_notebook_01(src_path, dst_path):
    nb = json.loads(Path(src_path).read_text(encoding="utf-8"))
    new_out = ("# OUTPUT_DIR is defined in the Drive-mount cell at the top of this notebook.\n"
               f'OUTPUT_DIR = Path("{BASELINE}")')

    replaced = 0
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        body = "".join(cell["source"])
        if OLD_OUT in body:
            cell["source"] = body.replace(OLD_OUT, new_out).splitlines(keepends=True)
            replaced += 1
        cell["outputs"] = []          # clear the old run so new output is unambiguous
        cell["execution_count"] = None
    assert replaced == 1, f"expected 1 OUTPUT_DIR assignment, patched {replaced}"

    nb["cells"].insert(0, {
        "cell_type": "code", "execution_count": None, "metadata": {},
        "outputs": [], "source": MOUNT_CELL.splitlines(keepends=True),
    })
    nb.setdefault("metadata", {}).setdefault("colab", {})["gpuType"] = "T4"
    nb["metadata"]["accelerator"] = "GPU"
    nb["metadata"].pop("widgets", None)

    Path(dst_path).write_text(json.dumps(nb, indent=1, ensure_ascii=False), encoding="utf-8")
    return len(nb["cells"])


def obtain_zip():
    """Reuse a zip already in Drive, else ask for one from this computer."""
    if SRC_DIR.exists():
        shutil.rmtree(SRC_DIR)
    SRC_DIR.mkdir(parents=True)

    candidates = sorted(PROJECT_DIR.glob("*.zip")) + sorted(
        Path("/content/drive/MyDrive").glob("*experiments*.zip"))

    if candidates:
        zip_path = candidates[0]
        print("Using zip already in Drive:", zip_path.name)
    else:
        from google.colab import files
        print("Select 'Frozen-DNABERT-initial -experiments.zip' from your computer.")
        uploaded = files.upload()
        name = next(iter(uploaded))
        zip_path = Path("/content") / name
        zip_path.write_bytes(uploaded[name])
        shutil.copy(zip_path, PROJECT_DIR / name)   # so a rerun skips the picker
        print("Uploaded:", name)

    with zipfile.ZipFile(zip_path) as zf:
        zf.extractall(SRC_DIR)

    found = sorted(p.name for p in SRC_DIR.iterdir())
    print(f"\nExtracted {len(found)} files:")
    for n in found:
        print(" -", n)
    missing = {f"0{i}" for i in range(1, 10)} - {n[:2] for n in found}
    assert not missing, f"missing notebooks: {sorted(missing)}"
    return found


def build():
    PROJECT_DIR.mkdir(parents=True, exist_ok=True)
    (PROJECT_DIR / "outputs").mkdir(exist_ok=True)
    obtain_zip()

    print("\nConverting Colab .py exports back into notebooks:")
    for src in sorted(SRC_DIR.glob("0*.py")):
        n_code, n_md, warnings = convert(src, PROJECT_DIR / (src.stem + ".ipynb"))
        print(f"  {src.name:52s} -> {n_code:3d} code + {n_md:3d} md cells")
        for w in warnings:
            print("      !! unparseable:", w)

    src01 = SRC_DIR / "01_Representation_baseline.ipynb"
    n_cells = patch_notebook_01(src01, PROJECT_DIR / src01.name)
    print(f"  {src01.name:52s} -> patched for Drive, {n_cells} cells")

    verify()


def verify():
    built = sorted(PROJECT_DIR.glob("0*.ipynb"))
    assert len(built) == 9, f"expected 9 notebooks, found {len(built)}"

    print(f"\n{'notebook':52s} {'cells':>6s} {'largest cell':>14s}")
    print("-" * 76)
    problems = 0
    for path in built:
        nb = json.loads(path.read_text(encoding="utf-8"))
        codes = ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]
        bad = [b for b in codes if not code_is_parseable(b)]
        problems += len(bad)
        flag = "" if not bad else f"  <-- {len(bad)} UNPARSEABLE"
        print(f"{path.name:52s} {len(nb['cells']):6d} {max(map(len, codes)):12d} B{flag}")

    nb01 = (PROJECT_DIR / "01_Representation_baseline.ipynb").read_text(encoding="utf-8")
    assert '"outputs/promoter_baseline_pilot"' not in nb01, "01 still writes a relative path"
    assert "drive.mount" in nb01, "01 does not mount Drive"

    print(f"\nUnparseable code cells: {problems}")
    print("01 mounts Drive and writes to the shared outputs/ path: OK")
    print("\nNotebook 02 will look for this file, which 01 must produce:")
    print("  " + BASELINE + "/dnabert_layer5_probe.joblib")
    print("\nReady. Open 01 on a T4 GPU runtime and run all cells, then 02 -> 09 in order.")


if __name__ == "__main__":
    build()
