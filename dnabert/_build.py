OLD_OUT = 'OUTPUT_DIR = Path("outputs/promoter_baseline_pilot")'


def stage_notebook_01(src_path, dst_path):
    nb = strip_outputs(json.loads(Path(src_path).read_text(encoding="utf-8")))
    new_out = ("# OUTPUT_DIR is defined in the Drive-mount cell at the top of this notebook.\n"
               f'OUTPUT_DIR = Path("{BASELINE}")')

    replaced = 0
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        body = "".join(cell["source"])
        if OLD_OUT in body:
            cell["source"] = body.replace(OLD_OUT, new_out).splitlines(keepends=True)
            replaced += 1
    assert replaced == 1, f"expected 1 relative OUTPUT_DIR in 01, patched {replaced}"

    nb["cells"].insert(0, {"cell_type": "code", "execution_count": None, "metadata": {},
                           "outputs": [], "source": MOUNT_CELL.splitlines(keepends=True)})
    nb.setdefault("metadata", {}).setdefault("colab", {})["gpuType"] = "T4"
    nb["metadata"]["accelerator"] = "GPU"
    write_nb(nb, dst_path)
    return nb


def unpack_zips():
    """Extract both zips; classify by content, not filename."""
    for sub in ("nb", "py"):
        d = WORK / sub
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)

    zips = sorted(PROJECT_DIR.glob("*.zip")) or sorted(
        Path("/content/drive/MyDrive").glob("*DNABERT*.zip"))
    if not zips:
        from google.colab import files
        print("Select BOTH zips (ctrl/cmd-click):")
        print("  - initial-DNABERT-experiments.zip        (the real notebooks)")
        print("  - Frozen-DNABERT-initial -experiments.zip (needed for notebook 02)")
        uploaded = files.upload()
        zips = []
        for name, blob in uploaded.items():
            p = PROJECT_DIR / name          # keep a copy so a rerun skips the picker
            p.write_bytes(blob)
            zips.append(p)

    for z in zips:
        with zipfile.ZipFile(z) as zf:
            names = zf.namelist()
            kind = "py" if any(n.endswith(".py") for n in names) else "nb"
            zf.extractall(WORK / kind)
            print(f"  {z.name}  ->  {len(names)} files ({kind})")

    # Drive appends ' (2)' etc. to duplicate downloads; normalise back.
    for p in list((WORK / "nb").iterdir()) + list((WORK / "py").iterdir()):
        clean = re.sub(r" \(\d+\)", "", p.name)
        if clean != p.name:
            p.rename(p.with_name(clean))


def build():
    PROJECT_DIR.mkdir(parents=True, exist_ok=True)
    (PROJECT_DIR / "outputs").mkdir(exist_ok=True)

    print("Unpacking:")
    unpack_zips()

    real = {p.name[:2]: p for p in (WORK / "nb").glob("*.ipynb")}
    exports = {p.name[:2]: p for p in (WORK / "py").glob("*.py")}
    assert "02" in exports, "02_...py not found; the Frozen zip is required for notebook 02"

    print("\nStaging notebooks:")
    for num in [f"0{i}" for i in range(1, 10)]:
        if num == "02":
            src = exports["02"]
            dst = PROJECT_DIR / (src.stem + ".ipynb")
            cells = convert_py(src, dst)
            n = sum(1 for c in cells if c["cell_type"] == "code")
            print(f"  {dst.name:52s} <- .py export, rebuilt ({n} code cells)")
            continue

        assert num in real, f"missing {num} in the notebooks zip"
        src = real[num]
        dst = PROJECT_DIR / src.name
        if num == "01":
            nb = stage_notebook_01(src, dst)
            print(f"  {dst.name:52s} <- real .ipynb, Drive-patched ({len(nb['cells'])} cells)")
        else:
            nb = strip_outputs(json.loads(src.read_text(encoding="utf-8")))
            nb.setdefault("metadata", {}).setdefault("colab", {})["gpuType"] = "T4"
            nb["metadata"]["accelerator"] = "GPU"
            write_nb(nb, dst)
            print(f"  {dst.name:52s} <- real .ipynb ({len(nb['cells'])} cells)")

    verify()


def verify():
    built = sorted(PROJECT_DIR.glob("0*.ipynb"))
    assert len(built) == 9, f"expected 9 notebooks, found {len(built)}"

    print(f"\n{'notebook':52s} {'cells':>6s} {'code':>5s} {'stale out':>10s}")
    print("-" * 78)
    problems = 0
    for path in built:
        nb = json.loads(path.read_text(encoding="utf-8"))
        codes = ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]
        stale = sum(1 for c in nb["cells"] if c.get("outputs"))
        bad = [b for b in codes if not code_is_parseable(b)]
        problems += len(bad) + stale
        flag = ""
        if bad:
            flag += f"  <-- {len(bad)} UNPARSEABLE"
        print(f"{path.name:52s} {len(nb['cells']):6d} {len(codes):5d} {stale:10d}{flag}")

    nb01 = (PROJECT_DIR / "01_Representation_baseline.ipynb").read_text(encoding="utf-8")
    assert '"outputs/promoter_baseline_pilot"' not in nb01, "01 still writes a relative path"
    assert "drive.mount" in nb01, "01 does not mount Drive"

    print(f"\nProblems: {problems}")
    print("01 mounts Drive and writes into the shared outputs/ path: OK")
    print("\nNotebook 02 will look for this file, which 01 must produce:")
    print("  " + BASELINE + "/dnabert_layer5_probe.joblib")
    print("\nReady. Open 01 on a T4 GPU runtime, run all cells, then 02 -> 09 in order.")
    print("Note: 06 restarts the runtime on purpose (os.kill). Remount and rerun 06 from the top.")


if __name__ == "__main__":
    build()
