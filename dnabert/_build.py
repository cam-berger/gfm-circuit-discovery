def code_is_parseable(body):
    """Parse-check, neutralising IPython magics only if the body needs it.

    Stripping magics first would corrupt multi-line strings whose contents happen to
    start with '!' or '%', so plain Python is tried before the magic-aware pass.
    """
    try:
        ast.parse(body)
        return True
    except SyntaxError:
        pass

    cleaned, skipping = [], False
    for line in body.split("\n"):
        if skipping:
            skipping = line.rstrip().endswith("\\")
            cleaned.append("pass")
        elif MAGIC.match(line):
            skipping = line.rstrip().endswith("\\")
            cleaned.append("pass")
        else:
            cleaned.append(line)
    try:
        ast.parse("\n".join(cleaned))
        return True
    except SyntaxError:
        return False


def split_blocks(text):
    """Yield (kind, body); 'md' for markdown blocks, 'code' otherwise.

    A triple quote only opens a markdown cell when it starts its own line. One opened
    mid-line belongs to code (e.g. `report = \"\"\"...\"\"\"`) and its closing quote often
    sits at column 0 -- that closer must not be read as an opener, so string state is
    tracked across the whole file rather than per line.
    """
    out, code_from, state = [], 0, None

    def flush_code(chunk):
        if chunk.strip():
            out.append(("code", chunk.strip("\n")))

    for m in DELIM.finditer(text):
        line_start = text.rfind("\n", 0, m.start()) + 1
        prefix = text[line_start:m.start()]
        if state is None:
            if prefix.lstrip().startswith("#"):
                continue
            is_md = prefix == ""
            if is_md:
                flush_code(text[code_from:line_start])
            state = (m.group(0), is_md, m.end())
        elif m.group(0) == state[0]:
            _, is_md, body_start = state
            if is_md:
                out.append(("md", text[body_start:m.start()].strip("\n")))
                code_from = m.end()
            state = None

    flush_code(text[code_from:])
    return [(k, b) for k, b in out if b.strip()]


def split_on_banners(body):
    """Split a merged code run at '# ====' section banners, top-level splits only.

    Colab marks no boundary between consecutive code cells, so they arrive merged.
    A split is taken only when the chunk before it parses on its own, which keeps the
    cut outside any function, loop, or literal.
    """
    lines = body.split("\n")
    starts = [i for i, ln in enumerate(lines)
              if i > 0 and BANNER.match(ln) and not lines[i - 1].strip()]
    if not starts:
        return [body]

    chunks, begin = [], 0
    for cut in starts:
        candidate = "\n".join(lines[begin:cut]).strip("\n")
        if candidate.strip() and code_is_parseable(candidate):
            chunks.append(candidate)
            begin = cut
    tail = "\n".join(lines[begin:]).strip("\n")
    if tail.strip():
        chunks.append(tail)
    return chunks or [body]


def looks_like_markdown(body):
    """Prose/heading-only block that does not parse as Python."""
    if code_is_parseable(body):
        return False
    for line in body.split("\n"):
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if re.match(r"^\d+\.\s|^[-*]\s|^>\s|^\|", s):
            continue
        if re.search(r"[=(){}\[\]]|^(import|from|def|class|return|print)\b", s):
            return False
    return True


def make_cell(kind, body):
    if kind == "md":
        return {"cell_type": "markdown", "metadata": {}, "source": body.split("\n")}
    return {"cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [], "source": body.split("\n")}


def convert_py(src_path, dst_path):
    text = re.sub(r"^# -\*- coding: utf-8 -\*-\s*\n", "",
                  Path(src_path).read_text(encoding="utf-8"), count=1)

    cells, first_md = [], True
    for kind, body in split_blocks(text):
        if kind == "md" and first_md:
            body, first_md = HEADER_BOILERPLATE.sub("", body).strip("\n"), False
            if not body.strip():
                continue
        if kind == "code" and looks_like_markdown(body):
            kind = "md"
        if kind == "md":
            cells.append(make_cell("md", body))
            continue
        for chunk in split_on_banners(body):
            cells.append(make_cell("code", chunk))

    for c in cells:
        c["source"] = [ln + "\n" for ln in c["source"][:-1]] + c["source"][-1:]
    write_nb({"cells": cells, "metadata": NB_META, "nbformat": 4, "nbformat_minor": 0},
             dst_path)
    return cells


